def classify_error(error: dict[str, Any]) -> str | None:
    """Map one finding to a recipe id, or ``None`` when nothing here applies.

    Accepts any of the three finding shapes -- compile error (``code``), missing
    reference (``kind``), package error (``kind``) -- because the repair loop
    classifies them through a single path. Never raises.
    """

    if not isinstance(error, dict):
        return None

    code = error.get("code")
    if isinstance(code, str):
        code = code.strip().upper()
        if code in _DELETE_FILE_CODES:
            return "delete-file"
        if code in _DEDUPE_TYPE_CODES:
            return "dedupe-type"
        if code in _MISSING_TYPE_CODES:
            return "resolve-missing-type"

    kind = error.get("kind")
    if isinstance(kind, str):
        kind = kind.strip().lower()
        if kind in _REMAP_GUID_KINDS:
            return "remap-guid"
        if kind in _RELAX_PACKAGE_KINDS:
            return "relax-package"

    return None


def _resolve_in_assets(project_path: Path, raw_path: str) -> tuple[Path | None, str | None]:
    """Resolve ``raw_path`` to a real path under ``<project>/Assets``.

    Returns ``(path, refusal_reason)``. Symlinks are resolved before the
    containment check, so a link pointing out of the project is refused.
    """

    project = Path(project_path).resolve()
    assets = (project / "Assets").resolve()
    candidate = Path(str(raw_path).replace("\\", "/"))
    if not candidate.is_absolute():
        candidate = project / candidate
    try:
        resolved = candidate.resolve()
    except OSError as exc:
        return None, f"cannot resolve path: {exc}"
    if resolved == assets or not resolved.is_relative_to(assets):
        return None, f"refusing to touch a path outside {assets}: {resolved}"
    return resolved, None


def apply_delete_file(project_path: Path, error: dict[str, Any]) -> dict[str, Any]:
    """Delete the source file named by a ``delete-file`` error, plus its ``.meta``.

    Guarded three ways, because this is the only destructive recipe implemented:
    the error must classify as ``delete-file`` (so an arbitrary error can never be
    turned into a deletion), the path must come from the error itself, and the
    resolved path must live under ``<project>/Assets``.
    """

    recipe = "delete-file"
    if classify_error(error) != recipe:
        return {
            "status": "refused",
            "recipe": recipe,
            "reason": f"error does not classify as {recipe}: code={error.get('code') if isinstance(error, dict) else None}",
        }

    raw_path = error.get("file") if isinstance(error, dict) else None
    if not raw_path:
        return {
            "status": "skipped",
            "recipe": recipe,
            "reason": "error carries no file path to delete",
        }

    target, refusal = _resolve_in_assets(Path(project_path), str(raw_path))
    if target is None:
        return {"status": "refused", "recipe": recipe, "reason": refusal, "path": str(raw_path)}
    if not target.is_file():
        return {
            "status": "skipped",
            "recipe": recipe,
            "reason": "file does not exist (already removed?)",
            "path": str(target),
        }

    deleted: list[str] = []
    try:
        target.unlink()
        deleted.append(str(target))
    except OSError as exc:
        return {"status": "error", "recipe": recipe, "reason": str(exc), "path": str(target)}

    meta = target.with_name(target.name + ".meta")
    if meta.is_file():
        try:
            meta.unlink()
            deleted.append(str(meta))
        except OSError:
            pass  # A stale .meta is harmless; Unity prunes it on the next import.

    return {
        "status": "applied",
        "recipe": recipe,
        "path": str(target),
        "deleted": deleted,
        "reason": f"{error.get('code')}: {error.get('message')}",
    }


