"""Prove a reconstructed Unity project actually opens, then repair it when it doesn't.

A composed project is a pile of files until an Editor has imported it. Everything
upstream -- AssetRipper output, ILSpy source, a hand-written manifest -- can look
complete on disk and still fail to open: duplicate ``[assembly: ...]`` attributes
from decompiled ``AssemblyInfo.cs`` (CS0579), types that reference assemblies that
were never copied into ``Plugins/`` (CS0246), MonoBehaviours whose script GUIDs
point at nothing. This module is the gate that turns "files exist" into "an Editor
imported it and reported N errors".

The load-bearing design decision is **no MCP bridge and no interactive Editor**.
An open Editor window only rescans the asset folder when its background scanner
gets around to it, and when the window lacks OS focus that can take minutes or
never happen at all -- a previous run of this pipeline stalled for a long time
waiting on exactly that. A cold ``-batchmode -quit -nographics`` open performs a
full import unconditionally, writes a deterministic log, and exits. So every
verification here goes through :func:`agentdecompile_recovery.tools.run_unity_batchmode`.

Three layers, deliberately separated so the fragile part is testable without Unity:

* the injected C# probe (:data:`VALIDATOR_SOURCE`) -- runs *inside* the Editor.
* pure parsers and the recipe classifier -- string in, dicts out, never raise.
* orchestration (:func:`validate_unity_project`, :func:`repair_unity_project`) --
  the only functions that spawn a process or touch the project tree.

Note the asymmetry that makes the log parsers indispensable: when compilation
fails, Unity refuses to invoke ``-executeMethod`` at all, so the JSON report is
never written and the *log* is the only evidence. A missing report is therefore a
finding, not an error.
"""

