# Raw string: the C# below contains backslash escapes that must survive verbatim.
VALIDATOR_SOURCE: str = r"""// <auto-generated>
// Written by agentdecompile_recovery.unity_editor.install_validator().
// Purpose: prove, from inside a batchmode Editor, that this project imports,
// compiles, and can open its scenes. Safe to delete; it is regenerated on every
// validation run and never referenced by game code.
// Target: Unity 2021.3+. Anything version-risky goes through reflection.
using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

public static class ADRecoveryValidate
{
    const string OutEnv = "ADRECOVERY_VALIDATE_OUT";
    const string Marker = "[ADRecoveryValidate]";

    // Cap the AssetDatabase fallback: a project with hundreds of scenes would
    // turn verification into an overnight job for no extra proof.
    const int MaxFallbackScenes = 64;

    public static void Run()
    {
        string outPath = ResolveOutPath();
        string json;
        try
        {
            json = BuildReport();
        }
        catch (Exception e)
        {
            json = "{\"schema\":\"adrecovery.validate.v1\",\"status\":\"error\",\"error\":\""
                 + Esc(e.GetType().Name + ": " + e.Message) + "\"}";
        }

        try
        {
            string dir = Path.GetDirectoryName(outPath);
            if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir)) Directory.CreateDirectory(dir);
            File.WriteAllText(outPath, json);
            Debug.Log(Marker + " wrote report: " + outPath);
        }
        catch (Exception e)
        {
            // The report is the whole point of this method; failing to write it
            // is the one internal failure worth a non-zero exit.
            Debug.LogError(Marker + " failed to write report to " + outPath + ": " + e.Message);
            EditorApplication.Exit(2);
            return;
        }
        EditorApplication.Exit(0);
    }

    static string ResolveOutPath()
    {
        string configured = null;
        try { configured = Environment.GetEnvironmentVariable(OutEnv); } catch { }
        if (!string.IsNullOrEmpty(configured)) return configured;
        // Application.dataPath is "<project>/Assets"; batchmode cwd is not reliable.
        string projectRoot;
        try { projectRoot = Path.GetDirectoryName(Application.dataPath); }
        catch { projectRoot = Directory.GetCurrentDirectory(); }
        return Path.Combine(Path.Combine(projectRoot, "Temp"), "adrecovery-validate.json");
    }

    static string BuildReport()
    {
        var scenePaths = new List<string>();
        var sceneEnabled = new List<bool>();
        string sceneSource = "buildSettings";
        string fatal = "";

        try
        {
            foreach (var entry in EditorBuildSettings.scenes)
            {
                if (entry == null || string.IsNullOrEmpty(entry.path)) continue;
                scenePaths.Add(entry.path);
                sceneEnabled.Add(entry.enabled);
            }
        }
        catch (Exception e) { fatal = e.GetType().Name + ": " + e.Message; }

        if (scenePaths.Count == 0)
        {
            // An empty build-settings list is common in reconstructed projects.
            // Falling back to on-disk scenes keeps the run from proving nothing;
            // sceneSource records which list was actually used.
            sceneSource = "assetDatabase";
            try
            {
                foreach (var guid in AssetDatabase.FindAssets("t:Scene"))
                {
                    string path = AssetDatabase.GUIDToAssetPath(guid);
                    if (string.IsNullOrEmpty(path)) continue;
                    if (!path.StartsWith("Assets/")) continue;
                    scenePaths.Add(path);
                    sceneEnabled.Add(false);
                    if (scenePaths.Count >= MaxFallbackScenes) break;
                }
            }
            catch (Exception e) { if (fatal.Length == 0) fatal = e.GetType().Name + ": " + e.Message; }
        }

        int opened = 0;
        int missingTotal = 0;
        var scenes = new StringBuilder();

        for (int i = 0; i < scenePaths.Count; i++)
        {
            string path = scenePaths[i];
            bool sceneOpened = false;
            int rootCount = 0;
            int missing = 0;
            string error = "";
            try
            {
                Scene scene = EditorSceneManager.OpenScene(path, OpenSceneMode.Single);
                sceneOpened = scene.IsValid();
                if (sceneOpened)
                {
                    opened++;
                    GameObject[] roots = scene.GetRootGameObjects();
                    rootCount = roots.Length;
                    for (int r = 0; r < roots.Length; r++) missing += CountMissingScripts(roots[r]);
                    missingTotal += missing;
                }
            }
            catch (Exception e)
            {
                error = e.GetType().Name + ": " + e.Message;
            }

            if (scenes.Length > 0) scenes.Append(",");
            scenes.Append("{\"path\":\"").Append(Esc(path)).Append("\"")
                  .Append(",\"enabled\":").Append(sceneEnabled[i] ? "true" : "false")
                  .Append(",\"opened\":").Append(sceneOpened ? "true" : "false")
                  .Append(",\"rootCount\":").Append(rootCount)
                  .Append(",\"missingScripts\":").Append(missing)
                  .Append(",\"error\":\"").Append(Esc(error)).Append("\"}");
        }

        var sb = new StringBuilder();
        sb.Append("{\"schema\":\"adrecovery.validate.v1\"")
          .Append(",\"status\":\"").Append(fatal.Length == 0 ? "ok" : "partial").Append("\"")
          .Append(",\"error\":\"").Append(Esc(fatal)).Append("\"")
          .Append(",\"unityVersion\":\"").Append(Esc(SafeUnityVersion())).Append("\"")
          .Append(",\"projectPath\":\"").Append(Esc(SafeProjectPath())).Append("\"")
          .Append(",\"sceneSource\":\"").Append(sceneSource).Append("\"")
          .Append(",\"sceneTotal\":").Append(scenePaths.Count)
          .Append(",\"scenesOpened\":").Append(opened)
          .Append(",\"missingScriptTotal\":").Append(missingTotal)
          .Append(",\"compile\":").Append(CompileStateJson())
          .Append(",\"scenes\":[").Append(scenes.ToString()).Append("]}");
        return sb.ToString();
    }

    static int CountMissingScripts(GameObject go)
    {
        if (go == null) return 0;
        int count = 0;
        try { count += UnityEditor.GameObjectUtility.GetMonoBehavioursWithMissingScriptCount(go); }
        catch { }
        Transform t = go.transform;
        for (int i = 0; i < t.childCount; i++) count += CountMissingScripts(t.GetChild(i).gameObject);
        return count;
    }

    static string CompileStateJson()
    {
        // scriptCompilationFailed has moved between public and internal across
        // versions, so read it reflectively rather than failing to compile.
        string failed = "null";
        try
        {
            PropertyInfo prop = typeof(EditorUtility).GetProperty(
                "scriptCompilationFailed",
                BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Static);
            if (prop != null)
            {
                object value = prop.GetValue(null, null);
                if (value is bool) failed = ((bool)value) ? "true" : "false";
            }
        }
        catch { failed = "null"; }

        bool isCompiling = false;
        try { isCompiling = EditorApplication.isCompiling; } catch { }

        int playerAssemblies = -1;
        int editorAssemblies = -1;
        try
        {
            playerAssemblies = UnityEditor.Compilation.CompilationPipeline
                .GetAssemblies(UnityEditor.Compilation.AssembliesType.Player).Length;
            editorAssemblies = UnityEditor.Compilation.CompilationPipeline
                .GetAssemblies(UnityEditor.Compilation.AssembliesType.Editor).Length;
        }
        catch { }

        return "{\"compilationFailed\":" + failed
             + ",\"isCompiling\":" + (isCompiling ? "true" : "false")
             + ",\"playerAssemblyCount\":" + playerAssemblies
             + ",\"editorAssemblyCount\":" + editorAssemblies + "}";
    }

    static string SafeUnityVersion()
    {
        try { return Application.unityVersion; } catch { return ""; }
    }

    static string SafeProjectPath()
    {
        try { return Path.GetDirectoryName(Application.dataPath); } catch { return ""; }
    }

    // Hand-rolled JSON escaping: JsonUtility cannot express a nested array of
    // objects without declaring serializable types, and Newtonsoft is not
    // guaranteed present in a reconstructed project.
    static string Esc(string value)
    {
        if (string.IsNullOrEmpty(value)) return "";
        var sb = new StringBuilder(value.Length + 16);
        foreach (char c in value)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (c < ' ') sb.Append("\\u").Append(((int)c).ToString("x4"));
                    else sb.Append(c);
                    break;
            }
        }
        return sb.ToString();
    }
}
"""


def install_validator(project_path: Path) -> Path:
    """Write the C# probe into ``<project>/Assets/Editor/`` and return its path.

    Rewritten on every call so a stale probe from an older version of this module
    can never silently determine the shape of a report.
    """

    target = Path(project_path) / VALIDATOR_RELATIVE_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(VALIDATOR_SOURCE, encoding="utf-8")
    return target


def validator_report_path(project_path: Path) -> Path:
    """Where the probe writes its JSON report when ``ADRECOVERY_VALIDATE_OUT`` is set."""

    return Path(project_path) / VALIDATOR_REPORT_RELATIVE_PATH


# ---------------------------------------------------------------------------
# Part 2 -- log parsing. Pure functions: string in, list of dicts out, never raise.
# ---------------------------------------------------------------------------

# A C# source path as it appears in a Unity compile error. Colons are excluded so
# the match cannot swallow a "Some prefix: " lead-in, with an explicit opt-in for
# a Windows drive letter.
_CS_FILE = r"(?:[A-Za-z]:[\\/])?[^\s:*?\"<>|\r\n][^:*?\"<>|\r\n]*?\.[cC][sS]"

_COMPILE_ERROR_RE = re.compile(
    rf"(?P<file>{_CS_FILE})\s*\(\s*(?P<line>\d+)\s*(?:,\s*(?P<column>\d+)\s*)?\)\s*:\s*"
    r"(?:error|ERROR|Error)\s+(?P<code>[A-Za-z]{1,4}\d{3,5})\s*:\s*(?P<message>[^\r\n]*)"
)

# Errors Unity reports without a file location (missing assembly references,
# csc driver errors). Still actionable, so they are captured with file=None.
_BARE_ERROR_RE = re.compile(
    r"(?<![\w.])(?:error|ERROR)\s+(?P<code>CS\d{3,5})\s*:\s*(?P<message>[^\r\n]*)"
)

# msbuild-style trailing project annotation, e.g. " [/path/Assembly-CSharp.csproj]".
_TRAILING_PROJECT_RE = re.compile(r"\s*\[[^\]\r\n]*\.(?:csproj|sln)\]\s*$")


def _clean_message(raw: str) -> str:
    return _TRAILING_PROJECT_RE.sub("", (raw or "").strip()).strip()


def _as_text(value: Any) -> str:
    if isinstance(value, str):
        return value
    if isinstance(value, (bytes, bytearray)):
        return value.decode("utf-8", "replace")
    if value is None:
        return ""
    try:
        return str(value)
    except Exception:  # noqa: BLE001 - a parser must never raise on weird input
        return ""


def parse_compile_errors(log_text: str) -> list[dict[str, Any]]:
    """Extract deduplicated C# compile errors from a Unity Editor log.

    Handles the canonical ``File.cs(line,col): error CSxxxx: message`` form plus
    the column-less and file-less variants Unity emits from different compiler
    drivers. Order of first appearance is preserved -- the first error is usually
    the causal one.
    """

    text = _as_text(log_text)
    if not text:
        return []

    out: dict[tuple[Any, ...], dict[str, Any]] = {}
    spans: list[tuple[int, int]] = []

    try:
        matches = list(_COMPILE_ERROR_RE.finditer(text))
    except Exception:  # noqa: BLE001
        matches = []
    for match in matches:
        spans.append(match.span())
        file_path = (match.group("file") or "").strip()
        column = match.group("column")
        entry = {
            "file": file_path or None,
            "line": int(match.group("line")),
            "column": int(column) if column is not None else None,
            "code": match.group("code").upper(),
            "message": _clean_message(match.group("message")),
        }
        out.setdefault(
            (entry["file"], entry["line"], entry["column"], entry["code"], entry["message"]),
            entry,
        )

    try:
        bare_matches = list(_BARE_ERROR_RE.finditer(text))
    except Exception:  # noqa: BLE001
        bare_matches = []
    for match in bare_matches:
        start = match.start()
        if any(begin <= start < end for begin, end in spans):
            continue
        entry = {
            "file": None,
            "line": None,
            "column": None,
            "code": match.group("code").upper(),
            "message": _clean_message(match.group("message")),
        }
        out.setdefault((None, None, None, entry["code"], entry["message"]), entry)

    return list(out.values())


# Unity's phrasing for a broken script reference varies by version and by whether
# the owning GameObject could be named at the point of the log write.
_MISSING_REFERENCE_PATTERNS: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(
            r"The referenced script(?:\s*\((?P<script>[^)\r\n]*)\))?\s+on this Behaviour"
            r"(?:\s*\((?:Game ?Object|GameObject)\s*'(?P<go>[^'\r\n]*)'\))?\s+is missing!?",
            re.IGNORECASE,
        ),
        "missing-script",
    ),
    (
        re.compile(
            r"(?:The referenced script|Script) (?:attached to|on) '(?P<go>[^'\r\n]*)'"
            r"[^\r\n]*?is missing[^\r\n]*",
            re.IGNORECASE,
        ),
        "missing-script",
    ),
    (
        re.compile(
            r"(?:Missing|Unknown)\s*\(\s*Mono\s*Script\s*\)(?:[^\r\n]*)",
            re.IGNORECASE,
        ),
        "missing-script",
    ),
    (
        re.compile(r"Missing GUID\s+(?P<guid>[0-9a-fA-F]{32})[^\r\n]*", re.IGNORECASE),
        "missing-guid",
    ),
    (
        re.compile(
            r"GUID\s+(?P<guid>[0-9a-fA-F]{32})[^\r\n]*?"
            r"(?:is missing|not found|cannot be found|could not be found)[^\r\n]*",
            re.IGNORECASE,
        ),
        "missing-guid",
    ),
    (
        re.compile(r"Could not extract GUID[^\r\n]*", re.IGNORECASE),
        "missing-guid",
    ),
    (
        re.compile(
            r"A script behaviour[^\r\n]*?(?:has a different serialization layout|"
            r"is missing|could not be loaded)[^\r\n]*",
            re.IGNORECASE,
        ),
        "script-layout-mismatch",
    ),
)

_ANY_GUID_RE = re.compile(r"\b([0-9a-fA-F]{32})\b")


def _scan_claimed_lines(
    text: str,
    patterns: tuple[tuple[re.Pattern[str], str], ...],
) -> list[tuple[str, re.Match[str], str]]:
    """Match ``patterns`` against ``text``, at most one hit per log line.

    Unity writes one diagnostic per line, and several of these patterns
    deliberately overlap (a generic tag plus a specific phrasing). Without this,
    a single failure would be reported two or three times and inflate every count
    the repair loop's convergence guard depends on. Patterns are tried in order,
    so the most specific one must come first.
    """

    claimed: set[int] = set()
    hits: list[tuple[int, str, re.Match[str], str]] = []
    for pattern, kind in patterns:
        try:
            matches = list(pattern.finditer(text))
        except Exception:  # noqa: BLE001 - a parser must never raise
            continue
        for match in matches:
            line_index = text.count("\n", 0, match.start())
            if line_index in claimed:
                continue
            claimed.add(line_index)
            line_start = text.rfind("\n", 0, match.start()) + 1
            line_end = text.find("\n", match.start())
            line_text = text[line_start : line_end if line_end != -1 else len(text)].strip()
            hits.append((line_index, kind, match, line_text))
    hits.sort(key=lambda hit: hit[0])
    return [(kind, match, line_text) for _, kind, match, line_text in hits]


def parse_missing_references(log_text: str) -> list[dict[str, Any]]:
    """Extract missing script / missing GUID reports, with repeat counts.

    Unity logs one line per broken Behaviour instance, so a single dead script can
    produce thousands of identical lines; ``occurrences`` keeps that signal without
    the volume.
    """

    text = _as_text(log_text)
    if not text:
        return []

    out: dict[tuple[Any, ...], dict[str, Any]] = {}
    for kind, match, line_text in _scan_claimed_lines(text, _MISSING_REFERENCE_PATTERNS):
        groups = match.groupdict()
        guid = groups.get("guid")
        if not guid:
            guid_match = _ANY_GUID_RE.search(line_text)
            guid = guid_match.group(1) if guid_match else None
        entry = {
            "kind": kind,
            "gameObject": (groups.get("go") or None),
            "script": (groups.get("script") or None),
            "guid": guid.lower() if guid else None,
            "message": (match.group(0) or "").strip(),
            "raw": line_text,
            "occurrences": 1,
        }
        key = (entry["kind"], entry["gameObject"], entry["script"], entry["guid"], entry["raw"])
        existing = out.get(key)
        if existing is None:
            out[key] = entry
        else:
            existing["occurrences"] += 1
    return list(out.values())


_PACKAGE_ID_RE = re.compile(r"\b((?:com|org|net)\.[A-Za-z0-9_.\-]+(?:@[^\s,;\]\"')]+)?)")

_PACKAGE_ERROR_PATTERNS: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(r"Failed to resolve packages?[:\s][^\r\n]*", re.IGNORECASE),
        "resolve-failed",
    ),
    (
        re.compile(r"An error occurred while resolving packages[:\s][^\r\n]*", re.IGNORECASE),
        "resolve-failed",
    ),
    (
        re.compile(r"Cannot find package[:\s]+[^\r\n]*", re.IGNORECASE),
        "package-not-found",
    ),
    (
        re.compile(r"Unable to (?:add|resolve|update) package[^\r\n]*", re.IGNORECASE),
        "package-add-failed",
    ),
    (
        re.compile(
            r"Package\s*\[?[A-Za-z0-9_.\-]+(?:@[^\s\]\r\n]+)?\]?[^\r\n]*?"
            r"(?:cannot be found|is not available|was not found|does not exist)[^\r\n]*",
            re.IGNORECASE,
        ),
        "package-not-found",
    ),
    (
        re.compile(r"\[Package Manager\][^\r\n]*", re.IGNORECASE),
        "package-manager",
    ),
    (
        re.compile(r"Package Manager[^\r\n]*?(?:Error|failed)[^\r\n]*", re.IGNORECASE),
        "package-manager",
    ),
)

# The bracketed [Package Manager] tag also fronts routine progress chatter, so a
# generic match only counts as an error when the line says something went wrong.
_PACKAGE_FAILURE_WORDS = re.compile(
    r"error|fail|cannot|could not|unable|unresolved|not available|not found", re.IGNORECASE
)
_GENERIC_PACKAGE_KINDS = {"package-manager"}


def parse_package_errors(log_text: str) -> list[dict[str, Any]]:
    """Extract UPM resolution failures from a Unity Editor log."""

    text = _as_text(log_text)
    if not text:
        return []

    out: dict[tuple[Any, ...], dict[str, Any]] = {}
    for kind, match, line_text in _scan_claimed_lines(text, _PACKAGE_ERROR_PATTERNS):
        message = (match.group(0) or "").strip()
        if kind in _GENERIC_PACKAGE_KINDS and not _PACKAGE_FAILURE_WORDS.search(line_text):
            continue
        package_match = _PACKAGE_ID_RE.search(line_text)
        package = package_match.group(1) if package_match else None
        entry = {
            "kind": kind,
            "package": package,
            "message": message,
            "raw": line_text,
            "occurrences": 1,
        }
        key = (kind, package, line_text)
        existing = out.get(key)
        if existing is None:
            out[key] = entry
        else:
            existing["occurrences"] += 1
    return list(out.values())


def summarize_log(log_text: str) -> dict[str, Any]:
    """Roll the three parsers into counts plus the findings themselves."""

    errors = parse_compile_errors(log_text)
    references = parse_missing_references(log_text)
    packages = parse_package_errors(log_text)

    codes: dict[str, int] = {}
    for error in errors:
        code = str(error.get("code") or "UNKNOWN")
        codes[code] = codes.get(code, 0) + 1

    kinds: dict[str, int] = {}
    for reference in references:
        kind = str(reference.get("kind") or "unknown")
        kinds[kind] = kinds.get(kind, 0) + int(reference.get("occurrences") or 1)

    return {
        "compileErrorCount": len(errors),
        "compileErrorCodes": codes,
        "compileErrors": errors,
        "missingReferenceCount": len(references),
        "missingReferenceOccurrences": sum(int(r.get("occurrences") or 1) for r in references),
        "missingReferenceKinds": kinds,
        "missingReferences": references,
        "packageErrorCount": len(packages),
        "packageErrors": packages,
        "clean": not errors and not packages,
    }


