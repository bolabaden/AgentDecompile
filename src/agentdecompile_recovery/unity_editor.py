_VALIDATE_CLAIM = (
    "proves only that the Editor opened this project in batchmode and reported the compile "
    "errors, scene opens, and missing script counts recorded above; it does not prove "
    "byte-identity with the shipped game, correct gameplay behavior, or that runtime-loaded "
    "(Resources/Addressables) content is intact"
)


def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _require_editor(editor: Path | None) -> Path:
    if editor is None:
        raise ToolchainError("unity-editor-missing", detail="no Unity Editor executable was provided")
    resolved = Path(editor).expanduser()
    if not resolved.is_file() or not os.access(resolved, os.X_OK):
        raise ToolchainError(
            "unity-editor-missing",
            detail=f"not an executable Unity Editor: {resolved}",
        )
    return resolved


def validate_unity_project(
    project_path: Path,
    *,
    editor: Path,
    timeout: int = 3600,
    log_dir: Path | None = None,
) -> dict[str, Any]:
    """Open a project in batchmode, run the injected probe, and report what broke.

    Two independent evidence sources are merged: the probe's JSON report (scene
    opens, root counts, missing-script counts) and the Editor log (compile errors,
    package failures). When compilation fails the Editor never invokes
    ``-executeMethod``, so ``validatorRan`` is false and the log carries the whole
    story -- which is the normal, expected path on a first pass.
    """

    project = Path(project_path).resolve()
    editor_path = _require_editor(editor)

    if not project.is_dir() or not (project / "Assets").is_dir():
        return {
            "schema": "agentdecompile.unity-validate.v1",
            "status": "error",
            "clean": False,
            "projectPath": str(project),
            "reason": "not a Unity project: no Assets/ directory under project path",
            "claimBoundary": "nothing was validated; the Editor was never launched",
        }

    report_path = validator_report_path(project)
    try:
        report_path.unlink()  # a stale report from a previous attempt would lie
    except OSError:
        pass
    report_path.parent.mkdir(parents=True, exist_ok=True)

    logs_dir = Path(log_dir) if log_dir is not None else project / "Logs"
    logs_dir.mkdir(parents=True, exist_ok=True)
    log_path = logs_dir / f"adrecovery-validate-{time.strftime('%Y%m%d-%H%M%S')}.log"

    validator_path = install_validator(project)

    previous_env = os.environ.get(VALIDATOR_OUT_ENV)
    os.environ[VALIDATOR_OUT_ENV] = str(report_path)
    started = time.monotonic()
    timed_out = False
    proc = None
    try:
        proc = run_unity_batchmode(
            editor_path,
            project,
            execute_method=VALIDATOR_METHOD,
            log_file=log_path,
            timeout=timeout,
        )
    except FileNotFoundError as exc:
        raise ToolchainError("unity-editor-missing", detail=str(exc)) from exc
    except subprocess.TimeoutExpired:
        # A hung import is a finding, not a crash: the partial log still parses.
        timed_out = True
    finally:
        if previous_env is None:
            os.environ.pop(VALIDATOR_OUT_ENV, None)
        else:
            os.environ[VALIDATOR_OUT_ENV] = previous_env
    duration = time.monotonic() - started

    log_text = _read_text(log_path)
    if proc is not None:
        log_text = "\n".join([log_text, proc.stdout or "", proc.stderr or ""])
    summary = summarize_log(log_text)

    report: dict[str, Any] | None = None
    if report_path.is_file():
        try:
            report = json.loads(_read_text(report_path))
        except (json.JSONDecodeError, ValueError):
            report = None
    validator_ran = isinstance(report, dict)

    scene_detail = list(report.get("scenes") or []) if validator_ran else []
    scenes = {
        "source": (report.get("sceneSource") if validator_ran else None),
        "total": int(report.get("sceneTotal") or 0) if validator_ran else 0,
        "opened": int(report.get("scenesOpened") or 0) if validator_ran else 0,
        "missingScriptTotal": int(report.get("missingScriptTotal") or 0) if validator_ran else 0,
        "detail": scene_detail,
    }

    compile_state = (report.get("compile") if validator_ran else None) or {}
    compilation_failed = compile_state.get("compilationFailed")
    if compilation_failed is None and not validator_ran:
        # The Editor declining to run -executeMethod *is* the compile-failure signal.
        compilation_failed = True if summary["compileErrorCount"] else None

    clean = bool(
        validator_ran
        and summary["compileErrorCount"] == 0
        and not compilation_failed
        and scenes["opened"] == scenes["total"]
    )

    if timed_out:
        status = "timeout"
    elif clean:
        status = "complete"
    else:
        status = "failed"

    return {
        "schema": "agentdecompile.unity-validate.v1",
        "status": status,
        "clean": clean,
        "projectPath": str(project),
        "editor": str(editor_path),
        "returnCode": (proc.returncode if proc is not None else None),
        "durationSeconds": round(duration, 2),
        "timedOut": timed_out,
        "validatorRan": validator_ran,
        "validatorPath": str(validator_path),
        "validatorMethod": VALIDATOR_METHOD,
        "reportPath": str(report_path) if validator_ran else None,
        "logPath": str(log_path),
        "unityVersion": (report.get("unityVersion") if validator_ran else None),
        "scenes": scenes,
        "compile": {
            "errorCount": summary["compileErrorCount"],
            "errorCodes": summary["compileErrorCodes"],
            "errors": summary["compileErrors"],
            "compilationFailed": compilation_failed,
            "editorAssemblyCount": compile_state.get("editorAssemblyCount"),
            "playerAssemblyCount": compile_state.get("playerAssemblyCount"),
        },
        "missingReferenceCount": summary["missingReferenceCount"],
        "missingReferences": summary["missingReferences"],
        "packageErrorCount": summary["packageErrorCount"],
        "packageErrors": summary["packageErrors"],
        "claimBoundary": _VALIDATE_CLAIM,
    }


def _findings(validation: dict[str, Any]) -> list[dict[str, Any]]:
    """Every classifiable finding from one validation, compile errors first."""

    findings: list[dict[str, Any]] = []
    findings.extend((validation.get("compile") or {}).get("errors") or [])
    findings.extend(validation.get("missingReferences") or [])
    findings.extend(validation.get("packageErrors") or [])
    return findings


def repair_unity_project(
    project_path: Path,
    *,
    editor: Path,
    max_attempts: int = 3,
    timeout: int = 3600,
) -> dict[str, Any]:
    """Validate, repair what has an implemented recipe, re-validate, repeat.

    Stops on the first of: a clean validation, no finding matching an implemented
    recipe, a compile-error count that failed to *decrease* since the previous
    attempt, or ``max_attempts`` validations. The non-convergence guard exists
    because a recipe that fires without helping would otherwise loop until the
    timeout -- burning an hour per attempt on a project that cannot be fixed here.
    """

    project = Path(project_path).resolve()
    attempts: list[dict[str, Any]] = []
    previous_count: int | None = None
    disposition = "max-attempts"
    unverified_repairs = False
    final: dict[str, Any] | None = None

    for attempt_index in range(1, max(1, int(max_attempts)) + 1):
        validation = validate_unity_project(project, editor=editor, timeout=timeout)
        final = validation
        error_count = int((validation.get("compile") or {}).get("errorCount") or 0)

        record: dict[str, Any] = {
            "attempt": attempt_index,
            "status": validation.get("status"),
            "errorCount": error_count,
            "missingReferenceCount": int(validation.get("missingReferenceCount") or 0),
            "packageErrorCount": int(validation.get("packageErrorCount") or 0),
            "scenesOpened": (validation.get("scenes") or {}).get("opened"),
            "scenesTotal": (validation.get("scenes") or {}).get("total"),
            "logPath": validation.get("logPath"),
            "recipesFired": {},
            "actions": [],
            "unfixable": [],
        }

        if validation.get("status") in {"error", "timeout"}:
            disposition = str(validation.get("status"))
            attempts.append(record)
            break

        if validation.get("clean"):
            disposition = "clean"
            unverified_repairs = False
            attempts.append(record)
            break

        if previous_count is not None and error_count >= previous_count:
            disposition = "non-convergent"
            record["note"] = (
                f"compile errors did not decrease ({previous_count} -> {error_count}); "
                "stopping rather than looping on an unfixable error"
            )
            attempts.append(record)
            break

        fired: dict[str, int] = {}
        actions: list[dict[str, Any]] = []
        unfixable: list[dict[str, Any]] = []
        applied_any = False

        for finding in _findings(validation):
            recipe = classify_error(finding)
            if recipe is None:
                unfixable.append({"reason": "no recipe matches this finding", "finding": finding})
                continue
            if recipe not in IMPLEMENTED_RECIPES:
                unfixable.append(
                    {
                        "reason": f"recipe '{recipe}' is not implemented",
                        "recipe": recipe,
                        "finding": finding,
                    }
                )
                continue
            applier = RECIPE_APPLIERS[recipe]
            result = applier(project, finding)
            actions.append(result)
            fired[recipe] = fired.get(recipe, 0) + 1
            if result.get("status") == "applied":
                applied_any = True
            else:
                unfixable.append(
                    {
                        "reason": f"recipe '{recipe}' returned {result.get('status')}: {result.get('reason')}",
                        "recipe": recipe,
                        "finding": finding,
                    }
                )

        record["recipesFired"] = fired
        record["actions"] = actions
        record["unfixable"] = unfixable
        attempts.append(record)

        if not applied_any:
            disposition = "no-recipe"
            break

        # A repair landed but has not been re-validated yet; only the next loop
        # iteration turns it into evidence.
        unverified_repairs = True
        previous_count = error_count
    else:
        disposition = "max-attempts"

    final_errors = list(((final or {}).get("compile") or {}).get("errors") or [])
    unfixed = [error for error in final_errors if classify_error(error) not in IMPLEMENTED_RECIPES]
    unimplemented: dict[str, int] = {}
    for error in unfixed:
        recipe = classify_error(error) or "unclassified"
        unimplemented[recipe] = unimplemented.get(recipe, 0) + 1

    if disposition == "clean":
        status = "complete"
    elif disposition in {"error", "timeout"}:
        status = "error"
    else:
        status = "failed"

    return {
        "schema": "agentdecompile.unity-repair.v1",
        "status": status,
        "disposition": disposition,
        "projectPath": str(project),
        "editor": str(Path(editor)),
        "maxAttempts": int(max_attempts),
        "attemptCount": len(attempts),
        "attempts": attempts,
        "finalErrorCount": int(((final or {}).get("compile") or {}).get("errorCount") or 0),
        "unfixedErrorCount": len(unfixed),
        "unfixedErrors": unfixed,
        "unimplementedRecipeCounts": unimplemented,
        "recipes": RECIPES,
        "implementedRecipes": sorted(IMPLEMENTED_RECIPES),
        "unverifiedRepairs": unverified_repairs,
        "finalValidation": final,
        "claimBoundary": (
            "records what the batchmode Editor reported before and after each applied repair; "
            + _VALIDATE_CLAIM
            + ". Repairs applied on the final attempt are unverified when unverifiedRepairs is true"
        ),
    }
